  static final Map<String, List<PlaceModel>> _statePlacesCache = {};
  static final Map<String, DateTime> _cacheTime = {};
  static const Duration _ttl = Duration(minutes: 5);

  /// Clear repository cache
  static void clearCache() {
    _statePlacesCache.clear();
    _cacheTime.clear();
  }

  /// Load places from Firestore 'places' collection for a given state
  static Future<List<PlaceModel>> getPlacesForState(
    String stateId, {
    bool forceRefresh = false,
  }) async {
    final normStateId = stateId.toLowerCase().trim();
    final normStateName = MalaysiaLocationService.getStateName(normStateId).toLowerCase();

    if (!forceRefresh &&
        _statePlacesCache.containsKey(normStateId) &&
        _cacheTime.containsKey(normStateId) &&
        DateTime.now().difference(_cacheTime[normStateId]!) < _ttl) {
      return _statePlacesCache[normStateId]!;
    }

    List<PlaceModel> results = [];

    try {
      // 1. Query Firestore 'places' collection
      final placesSnap = await AppServices.db.collection('places').get();

      for (final doc in placesSnap.docs) {
        final place = PlaceModel.fromFirestore(doc);
        if (!place.isActive) continue;

        final pStateId = place.stateId.toLowerCase().trim();
        final pStateName = place.stateName.toLowerCase().trim();

        // Strictly check that place belongs to the selected state
        if (pStateId == normStateId ||
            pStateName == normStateName ||
            pStateName == normStateId ||
            pStateId == normStateName) {
          results.add(place);
        }
      }

      // 2. Query Firestore 'vendors' collection for active registered vendors in same state
      try {
        final vendorsSnap = await AppServices.db.collection('vendors').get();
        for (final doc in vendorsSnap.docs) {
          final data = doc.data();
          if (data['status'] != null && data['status'] != 'active') continue;

          final vState = '${data['state'] ?? data['stateName'] ?? ''}'.toLowerCase().trim();
          final vAddress = '${data['address'] ?? data['formattedAddress'] ?? data['area'] ?? ''}'.toLowerCase();

          bool stateMatch = vState == normStateId || vState == normStateName;
          if (!stateMatch && (vAddress.contains(normStateName) || vAddress.contains(normStateId))) {
            stateMatch = true;
          }

          if (stateMatch) {
            final vendorPlace = PlaceModel.fromMap('vendor_${doc.id}', {
              ...data,
              'vendorId': doc.id,
              'stateId': normStateId,
              'stateName': MalaysiaLocationService.getStateName(normStateId),
              'trustLabel': 'Verified Vendor',
            });
            // Avoid duplicate vendor names
            if (!results.any((p) => p.name.toLowerCase() == vendorPlace.name.toLowerCase())) {
              results.add(vendorPlace);
            }
          }
        }
      } catch (_) {
        // Vendors collection optional
      }
    } catch (_) {
      // Firestore query failed or empty
    }

    _statePlacesCache[normStateId] = results;
    _cacheTime[normStateId] = DateTime.now();
    return results;
  }

  /// Search places for adding in edit itinerary screen strictly for a given state
  static Future<List<PlaceModel>> searchPlacesForAdding({
    required String stateId,
    String area = '',
    List<String> interests = const [],
    String query = '',
    List<String> excludedPlaceIds = const [],
  }) async {
    final allPlaces = await getPlacesForState(stateId);
    final excludedSet = excludedPlaceIds.toSet();
    final qLower = query.toLowerCase().trim();
    final cleanArea = area.split(',').first.toLowerCase().trim();
    final mustStayInArea =
        cleanArea.isNotEmpty &&
        !const {
          'all',
          'all areas',
          'all places',
          'statewide',
          'malaysia',
        }.contains(_areaKey(cleanArea));

    bool isMatchingArea(PlaceModel place) {
      if (cleanArea.isEmpty) return true;
      final pArea = place.area.toLowerCase();
      final pAddr = place.formattedAddress.toLowerCase();
      final pName = place.name.toLowerCase();

      if (_mentionsOtherKnownArea(
        pAddr,
        selectedArea: cleanArea,
        stateId: stateId,
      )) {
        return false;
      }

      final normTarget = cleanArea.replaceAll(' ', '').replaceAll('-', '');
      final normArea = pArea.replaceAll(' ', '').replaceAll('-', '');
      final normAddr = pAddr.replaceAll(' ', '').replaceAll('-', '');

      if (normArea.contains(normTarget) || normTarget.contains(normArea)) return true;
      if (normAddr.contains(normTarget) || pAddr.contains(cleanArea)) return true;
      if (pName.contains(cleanArea)) return true;
      return false;
    }

    final filtered = allPlaces.where((place) {
      if (excludedSet.contains(place.placeId)) return false;
      if (mustStayInArea && !isMatchingArea(place)) return false;

      // Filter by search query if provided
      if (qLower.isNotEmpty) {
        final searchable = '${place.name} ${place.category} ${place.area} ${place.formattedAddress} ${place.description} ${place.interestTags.join(" ")}'.toLowerCase();
        if (!searchable.contains(qLower)) return false;
      }

      // If no text query and interests are specified, filter by interest
      if (qLower.isEmpty && interests.isNotEmpty) {
        final matchesInterest = place.interestTags.any((t) => interests.any((i) => i.toLowerCase() == t.toLowerCase())) ||
            interests.any((i) => i.toLowerCase() == place.category.toLowerCase());
        if (!matchesInterest) return false;
      }

      return true;
    }).toList();

    // Sort: Matching area first, then verified and highest public rating
    filtered.sort((a, b) {
      final aArea = isMatchingArea(a);
      final bArea = isMatchingArea(b);

      if (aArea && !bArea) return -1;
      if (!aArea && bArea) return 1;

      final scoreA = a.publicRating + (a.isVerified ? 0.5 : 0.0);
      final scoreB = b.publicRating + (b.isVerified ? 0.5 : 0.0);
      return scoreB.compareTo(scoreA);
    });

    return filtered;
  }

  static bool _mentionsOtherKnownArea(
    String value, {
    required String selectedArea,
    required String stateId,
  }) {
    final valueKey = _areaKey(value);
    if (valueKey.isEmpty) return false;

    final selectedAliases = _areaAliases(selectedArea);
    final knownAreas = _knownAreaNamesForState(stateId);
    for (final knownArea in knownAreas) {
      final aliases = _areaAliases(knownArea);
      if (aliases.any(selectedAliases.contains)) continue;
      if (aliases.any((alias) => _containsAreaTerm(valueKey, alias))) {
        return true;
      }
    }
    return false;
  }

  static List<String> _knownAreaNamesForState(String stateId) {
    final normalizedStateId = MalaysiaLocationService.normalizeStateId(stateId);
    final state = MalaysiaLocationService.defaultStates.firstWhere(
      (item) => item.id == normalizedStateId,
      orElse: () => const MalaysianStateItem(id: '', name: '', areas: []),
    );
    final areas = <String>{...state.areas};
    if (normalizedStateId == 'penang') {
      areas.addAll(const ['Air Itam', 'Ayer Itam', 'Penang Hill']);
    }
    return areas.toList();
  }

  static Set<String> _areaAliases(String value) {
    final key = _areaKey(value);
    if (key.isEmpty) return const {};

    final aliases = <String>{key};
    final withoutParentheses = _areaKey(
      value.replaceAll(RegExp(r'\([^)]*\)'), ' '),
    );
    if (withoutParentheses.isNotEmpty) aliases.add(withoutParentheses);

    for (final part in value.split(RegExp(r'[/&,]'))) {
      final partKey = _areaKey(part);
      if (partKey.length > 2) aliases.add(partKey);
    }

    switch (key) {
      case 'george town':
        aliases.addAll(const [
          'georgetown',
          'unesco core',
          'armenian street',
          'lebuh armenian',
          'love lane',
          'chulia street',
          'little india',
          'carnarvon',
          'campbell street',
          'church street',
          'lebuh pantai',
          'beach street',
          'weld quay',
          'jalan penang',
        ]);
        break;
      case 'air itam':
      case 'ayer itam':
      case 'penang hill':
        aliases.addAll(const [
          'air itam',
          'ayer itam',
          'penang hill',
          'bukit bendera',
          'kek lok si',
        ]);
        break;
      case 'melaka city bandar hilir':
        aliases.addAll(const ['melaka city', 'bandar hilir']);
        break;
      case 'jonker walk heritage core':
        aliases.addAll(const ['jonker walk', 'jonker']);
        break;
      case 'klcc city centre':
        aliases.addAll(const ['klcc', 'city centre', 'kuala lumpur city centre']);
        break;
      case 'chinatown petaling street':
        aliases.addAll(const ['chinatown', 'petaling street']);
        break;
      case 'brickfields little india':
        aliases.addAll(const ['brickfields', 'little india']);
        break;
      case 'kundasang ranau':
        aliases.addAll(const ['kundasang', 'ranau']);
        break;
      case 'langkawi kuah cenang':
        aliases.addAll(const ['langkawi', 'kuah', 'cenang']);
        break;
      case 'kuching waterfront old town':
        aliases.addAll(const ['kuching', 'kuching waterfront', 'old town']);
        break;
      case 'bau wind caves':
        aliases.addAll(const ['bau', 'wind caves']);
        break;
    }

    return aliases;
  }

  static bool _containsAreaTerm(String valueKey, String term) {
    final termKey = _areaKey(term);
    if (valueKey.isEmpty || termKey.isEmpty) return false;
    if (termKey.length <= 2) {
      return valueKey.split(' ').contains(termKey);
    }
    return valueKey == termKey || valueKey.contains(termKey);
  }

  static String _areaKey(String value) {
    return value
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
  }

  /// Seed initial heritage places into Firestore if the places collection is empty
  static Future<int> seedInitialPlacesIfEmpty({bool force = false}) async {
    try {
      final snap = await AppServices.db.collection('places').limit(5).get();
      if (snap.docs.isNotEmpty && !force) {
        return 0; // Already seeded
      }

      final initialData = _getHeritageCatalogue();
      final batch = AppServices.db.batch();

      for (final item in initialData) {
        final docRef = AppServices.db.collection('places').doc(item['placeId']);
        batch.set(docRef, {
          ...item,
          'createdAt': FieldValue.serverTimestamp(),
          'updatedAt': FieldValue.serverTimestamp(),
        }, SetOptions(merge: true));
      }

      await batch.commit();
      clearCache();
      return initialData.length;
    } catch (e) {
      return 0;
    }
  }

